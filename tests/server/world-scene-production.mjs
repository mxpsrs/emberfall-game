import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import {handleEditorEdits,editorAccess} from '../../worker/editor.js';

const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE game_accounts(id TEXT PRIMARY KEY,username TEXT); CREATE TABLE game_sessions(token_hash TEXT PRIMARY KEY,account_id TEXT,expires_at INTEGER); CREATE TABLE character_saves(user_id TEXT PRIMARY KEY,state TEXT); CREATE TABLE editor_world(id INTEGER PRIMARY KEY,revision INTEGER,document TEXT,previous_document TEXT,updated_by TEXT);');
