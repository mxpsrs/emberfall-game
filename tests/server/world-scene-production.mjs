assert.equal(initial.sha256,createHash('sha256').update(JSON.stringify(initial.edits,null,2)+'\n').digest('hex'));
assert.equal(initial.worldSha256,createHash('sha256').update(JSON.stringify(initial.world,null,2)+'\n').digest('hex'));
const legacyDb=new DatabaseSync(':memory:');legacyDb.exec('CREATE TABLE editor_world(id INTEGER PRIMARY KEY,revision INTEGER,document TEXT,previous_document TEXT,updated_by TEXT);');
const legacyText=fs.readFileSync(new URL('../../editor-data/world-edits.json',import.meta.url),'utf8'),legacyRevision=JSON.parse(legacyText).revision;
legacyDb.prepare('INSERT INTO editor_world VALUES (1,?,?,?,?)').run(legacyRevision,legacyText,null,owner);
const migratedRow=await (await handleEditorEdits(request(),environment(legacyDb))).json();
assert.deepEqual(migratedRow.world,initial.world,'an existing version 1 editor row migrates to the canonical version 2 seed');
legacyDb.close();
const edit={scene:'overworld',kind:'object',id:'new-light',name:'Lantern',x:10,y:11,rotation:45,scale:1,created:true,data:{id:'new-light',type:'prop',name:'Lantern',editorAsset:{source:'briar',key:'lantern'}}};
