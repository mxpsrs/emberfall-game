db.prepare('INSERT INTO character_saves VALUES (?,?)').run('untouched','existing character');
const environment=database=>({DB:{prepare(sql){return {bind(...args){return {async first(){return database.prepare(sql).get(...args)||null},async run(){return {meta:{changes:database.prepare(sql).run(...args).changes}}}}}}}}});
const env=environment(db);
const request=(method='GET',body,authenticated=false)=>new Request('https://veldren.test/api/editor/edits',{method,headers:{origin:'https://veldren.test',...(authenticated?{cookie:'ember_session='+token}:{}),'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
assert.equal((await editorAccess(request(),env)).status,403);
assert.equal((await editorAccess(request('GET',null,true),env)).status,200);
const initial=await (await handleEditorEdits(request(),env)).json();
assert.equal(initial.world.format,'veldren.world');assert.equal(initial.edits.version,1);
assert.deepEqual(initial.world,JSON.parse(fs.readFileSync(new URL('../../editor-data/world-scene.json',import.meta.url),'utf8')),'production seed uses the canonical v2 document');
