const staleFirstSave=structuredClone(initial.world);staleFirstSave.expectedRevision=initial.revision-1;
assert.equal((await handleEditorEdits(request('PUT',staleFirstSave,true),env)).status,409,'an empty editor row still rejects a stale canonical document');
const written=await handleEditorEdits(request('PUT',input,true),env);assert.equal(written.status,200);
const saved=await written.json(),world=JSON.parse(db.prepare('SELECT document FROM editor_world').get().document);
