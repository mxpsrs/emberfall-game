'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('client/view3d.js','utf8');
const start=source.indexOf('let meshDetail3=1;');
const end=source.indexOf('function painter3',start);
assert(start>=0&&end>start,'static mesh helpers are present');
let now=0;
const context={Map,WeakMap,performance:{now:()=>now}};
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
const buildKey={},deferredKey={};let builds=0,submitted=0;
const build=collector=>{builds++;collector.face([[0,0,0],[1,0,0],[0,1,0]],'#ffffff');return 2;};
vm.runInContext('staticMeshDeadline3=10',context);
const first=context.cachedMesh3(buildKey,'prop',build);
assert.equal(first.deferred,undefined);assert.equal(first.height,2);assert.equal(builds,1);
now=11;
const deferred=context.cachedMesh3(deferredKey,'prop',build);
assert.equal(deferred.deferred,true);assert.equal(deferred.height,null);assert.equal(builds,1);
assert.equal(context.emitMesh3({face(){submitted++;}},deferred),null);
assert.equal(submitted,0,'deferred geometry emits neither faces nor an invisible pick result');
vm.runInContext('staticMeshDeadline3=20',context);
const streamed=context.cachedMesh3(deferredKey,'prop',build);
assert.equal(streamed.deferred,undefined);assert.equal(streamed.height,2);assert.equal(builds,2);
assert.equal(context.emitMesh3({face(){submitted++;}},streamed),2);
assert.equal(submitted,1);
now=30;vm.runInContext('staticMeshDeadline3=0',context);
assert.equal(context.cachedMesh3(deferredKey,'prop',build),streamed,'built geometry remains available after the frame budget expires');
assert.equal(builds,2);
assert(source.includes('visibility.tiles<=7?10:16'),'mobile and desktop receive bounded per-frame budgets');
assert(source.includes('if(cached.deferred)continue;')&&source.includes('if(height===null)continue;'),'deferred static meshes do not receive hitboxes or labels');
console.log('PASS: static meshes defer at the frame budget, stream on later frames, and remain cached after construction.');
